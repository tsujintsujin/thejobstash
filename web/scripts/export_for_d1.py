# -*- coding: utf-8 -*-
"""
Dump the local jobstash.db into SQL that `wrangler d1 execute --file` can load.

    python scripts/export_for_d1.py            # everything
    python scripts/export_for_d1.py --jobs     # the shared pool only

Why not `sqlite3 .dump`: that emits the CREATE TABLE statements and the
PRAGMAs too, which would fight the migration that already built the schema.
This writes INSERTs only, with `INSERT OR REPLACE` so re-running it is safe.

Rows are batched into multi-row VALUES statements because D1's HTTP path
charges per statement, not per row - 1,700 individual INSERTs is slow enough
to look broken.
"""
import argparse, io, os, sqlite3, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, ROOT)

DB = os.environ.get("JOBSTASH_DB", os.path.join(ROOT, "jobstash.db"))
# NOT in migrations/ - wrangler scans that directory, and this is data, not a
# migration. It also carries real emails, password hashes and session tokens,
# so it stays out of anything that gets committed.
OUT = os.path.join(HERE, "..", "seed.sql")

# Order matters: users before anything referencing users.
TABLES = ["jobs", "users", "profiles", "payments", "runs",
          "deliveries", "trial_runs", "sessions"]
# Cap each INSERT by BYTES, not by row count. Job descriptions run to several
# kilobytes each, so a fixed 50 rows produced statements D1 rejected outright
# with SQLITE_TOOBIG. 80 KB leaves room under the limit while still keeping the
# statement count low enough that 2,000 rows load in one pass.
MAX_STATEMENT_BYTES = 80000


def lit(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, bytes):
        v = v.decode("utf-8", "replace")
    return "'" + str(v).replace("'", "''") + "'"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--jobs", action="store_true",
                    help="only the shared job pool, no accounts")
    args = ap.parse_args()

    tables = ["jobs"] if args.jobs else TABLES

    conn = sqlite3.connect(DB)
    conn.row_factory = sqlite3.Row
    parts = ["-- Generated by scripts/export_for_d1.py. INSERTs only; the\n"
             "-- schema comes from 0001_init.sql.\n"]
    total = 0

    for table in tables:
        try:
            rows = conn.execute("SELECT * FROM %s" % table).fetchall()
        except sqlite3.OperationalError:
            continue                      # table not in this database yet
        if not rows:
            continue
        cols = rows[0].keys()
        collist = ",".join(cols)
        head = "INSERT OR REPLACE INTO %s (%s) VALUES\n  " % (table, collist)
        parts.append("\n-- %s (%d rows)" % (table, len(rows)))

        chunk, size = [], 0
        for r in rows:
            tup = "(" + ",".join(lit(r[c]) for c in cols) + ")"
            # A row bigger than the cap on its own still has to go out whole -
            # it cannot be split, and D1 takes it.
            if chunk and size + len(tup) > MAX_STATEMENT_BYTES:
                parts.append(head + ",\n  ".join(chunk) + ";")
                chunk, size = [], 0
            chunk.append(tup)
            size += len(tup) + 4
        if chunk:
            parts.append(head + ",\n  ".join(chunk) + ";")
        total += len(rows)

    conn.close()
    io.open(OUT, "w", encoding="utf-8").write("\n".join(parts) + "\n")
    size = os.path.getsize(OUT) / 1048576.0
    print("wrote %s - %d rows across %d tables, %.1f MB"
          % (os.path.normpath(OUT), total, len(tables), size))
    print("load it with:  npx wrangler d1 execute jobstash --remote "
          "--file=seed.sql")


if __name__ == "__main__":
    main()
